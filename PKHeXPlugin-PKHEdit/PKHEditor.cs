    private void ImportPkm(PKM pk, string source)
    {
        if (pkh == null)
        {
            CreateFrom(pk, source);
            return;
        }

        var plan = PkhService.PlanImport(pkh, pk, CHK_UseCustomTracker.Checked);
        // Original gate kept below for easy revert: pure PKHeX conversions were applied directly,
        // with the report only in the status tooltip. AlwaysShowImportDialog short-circuits it now.
        bool discardItem = false;
        if ((AlwaysShowImportDialog || plan.IsBlocked || plan.NeedsConfirm)
            && !ImportReportDialog.Confirm(this, plan, $"Import {pk.GetType().Name} from {source}", Font, pk.HeldItem != 0, out discardItem))
        {
            L_Status.Text = "Import cancelled.";
            return;
        }
        if (plan.IsBlocked)
            return;
        toolTip1.SetToolTip(L_Status, string.Join(Environment.NewLine, plan.Items.Select(i => $"[{i.Group}] {i.Text}")));

        // The PKH never keeps the incoming item (Core.CopyFrom skips HeldItem): return it to the bag
        // unless the dialog's "Don't return item" was chosen — on failure the user picks cancel/continue.
        string bagNote = "";
        if (pk.HeldItem != 0 && !discardItem)
        {
            if (PkhService.TryReturnItemToBag(saveProvider.SAV, pk, out var bagItem))
            {
                bagNote = $" Held item {bagItem} returned to the bag.";
            }
            else if (!ConfirmImportWithoutItem(bagItem))
            {
                L_Status.Text = "Import cancelled.";
                return;
            }
            // Continue: the failed attempt left the save untouched, the item simply isn't recovered.
        }

        var target = PKH.GetType(pk is PK7 ? typeof(PK8) : pk.GetType());
        pkh = plan.Result;
        if (target != HomeGameDataFormat.None)
            selected = target;
        dirty = true;
        L_Status.Text = $"Imported {pk.GetType().Name} from {source}.{bagNote}";
        RefreshAll();
    }

    private void CreateFrom(PKM pk, string source)
    {
        PKH created;
        bool generated;
        try
        {
            created = PkhService.Create(pk, CHK_UseCustomTracker.Checked, out generated);
        }
        catch (Exception ex)
        {
            MessageBox.Show(this, $"PKHeX could not create a PKH from this {pk.GetType().Name}: {ex.Message}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Error);
            return;
        }

        var note = generated
            ? $" No HOME tracker: generated {created.Tracker:X16}."
            : created.Tracker != 0 ? $" HOME tracker {created.Tracker:X16} kept." : " No HOME tracker (custom tracker off).";
        if (PKH.GetType(pk is PK7 ? typeof(PK8) : pk.GetType()) == HomeGameDataFormat.None && pk is not PK7)
            note += $" {pk.GetType().Name} has no HOME version data; only shared data was stored.";

        // No PKH is loaded yet: never touch the bag here. The source PKM stays intact, so dropping
        // the same file again after this import runs the normal return-item flow against the new PKH.
        string bagNote = pk.HeldItem != 0
            ? " Held item was not returned — drop the same PKM again to send it to the bag."
            : "";
        SetPkh(created, null, true, $"Created PKH from {pk.GetType().Name} ({source}).{note}{bagNote}");
    }

    /// <summary>Shown when the held item couldn't reach the bag: true = import anyway without the item.</summary>
    private bool ConfirmImportWithoutItem(string reason) =>
        MessageBox.Show(this,
            $"The held item could not be returned to the bag ({reason}).{Environment.NewLine}{Environment.NewLine}" +
            "Continue the import anyway? The item will not be stored in the PKH. (Yes = import anyway, No = cancel)",
            BaseTitle, MessageBoxButtons.YesNo, MessageBoxIcon.Warning, MessageBoxDefaultButton.Button2) == DialogResult.Yes;

    #endregion

    #region Drag & drop

    private void OnDragEnter(object? sender, DragEventArgs e)
    {
        bool accept = e.Data?.GetDataPresent(DataFormats.FileDrop) == true && e.AllowedEffect.HasFlag(DragDropEffects.Copy);
        // Must be Copy: PKHeX's box slots treat Link as "moved to another slot".
        e.Effect = accept ? DragDropEffects.Copy : DragDropEffects.None;
    }

    private void OnDragDrop(object? sender, DragEventArgs e)
    {
        if (e.Data?.GetData(DataFormats.FileDrop) is not string[] { Length: not 0 } files)
            return;
        // Defer so the drag source (a PKHeX slot) is released before any dialog opens.
        var path = files[0];
        BeginInvoke(() => HandleDroppedFile(path));
    }

    private void HandleDroppedFile(string path)
    {
        if (PkhService.TryLoad(path, out _, out _))
        {
            OpenFile(path);
            return;
        }
        if (!PkmUtil.TryLoadPkm(path, saveProvider.SAV, out var pk, out var error))
        {
            MessageBox.Show(this, $"Unable to load \"{Path.GetFileName(path)}\": {error}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Warning);
            return;
        }
        ImportPkm(pk, Path.GetFileName(path));
    }

    #endregion

    #region Editing

    private void Edit(Action<PKH> change, string what)
    {
        if (loading || pkh == null || PkhService.HasPC9(pkh))
            return;
        change(pkh);
        dirty = true;
        L_Status.Text = $"Edited {what}.";
        RefreshAll();
    }

    private void TB_Nickname_Validated(object? sender, EventArgs e)
    {
        if (pkh == null || TB_Nickname.Text == pkh.Nickname)
            return;
        Edit(p =>
        {
            p.Nickname = TB_Nickname.Text;
            p.IsNicknamed = !string.IsNullOrEmpty(TB_Nickname.Text);
        }, "nickname");
    }

    private void NUD_EXP_ValueChanged(object? sender, EventArgs e)
    {
        if (pkh == null || (uint)NUD_EXP.Value == pkh.EXP)
            return;
        Edit(p => p.EXP = (uint)NUD_EXP.Value, "EXP");
    }

    private void CB_Nature_SelectionChangeCommitted(object? sender, EventArgs e)
    {
        // Items are localized strings built in enum order, so the selected index is the Nature value.
        if (pkh == null || (uint)CB_Nature.SelectedIndex > (uint)Nature.Quirky || (Nature)CB_Nature.SelectedIndex == pkh.Nature)
            return;
        var n = (Nature)CB_Nature.SelectedIndex;
        Edit(p => p.Nature = n, "nature");
    }

    private void NUD_Friendship_ValueChanged(object? sender, EventArgs e)
    {
        if (pkh == null || (byte)NUD_Friendship.Value == pkh.CurrentFriendship)
            return;
        Edit(p => p.CurrentFriendship = (byte)NUD_Friendship.Value, "friendship");
    }

    private void TB_Tracker_Validated(object? sender, EventArgs e)
    {
        if (pkh == null)
            return;
        if (!ulong.TryParse(TB_Tracker.Text.Trim(), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var value))
        {
            TB_Tracker.Text = pkh.Tracker.ToString("X16");
            return;
        }
        if (value != pkh.Tracker)
            Edit(p => p.Tracker = value, "HOME tracker");
    }

    private void B_NewTracker_Click(object? sender, EventArgs e)
    {
        if (pkh == null)
            return;
        if (pkh.Tracker != 0 && !PkhService.IsGeneratedTracker(pkh.Tracker)
            && MessageBox.Show(this, $"Replace the HOME-assigned tracker {pkh.Tracker:X16} with a generated one?", BaseTitle, MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes)
        {
            return;
        }
        // A new tracker on an existing PKH makes future imports look like a different Pokémon (see GetIdentity).
        if (PkhService.GetVersions(pkh).Count != 0
            && MessageBox.Show(this, "This PKH already has exported version data. Changing the tracker may make future PKM imports look like a different Pokémon. Continue?", BaseTitle, MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes)
        {
            return;
        }
        Edit(p => p.Tracker = PkhService.NewTracker(), "HOME tracker");
    }

    private void B_ClearTracker_Click(object? sender, EventArgs e)
    {
        if (pkh == null)
            return;
        if (pkh.Tracker != 0
            && MessageBox.Show(this, $"Clear the HOME tracker {pkh.Tracker:X16}? It will be set to 0.", BaseTitle, MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes)
        {
            return;
        }
        Edit(p => p.Tracker = 0, "HOME tracker");
    }

    // Persist the mode in the HOME metadata file, then re-evaluate the Gen button (and anything else gated on it).
    private void CHK_UseCustomTracker_CheckedChanged(object? sender, EventArgs e)
    {
        HomeStorage.SetUseCustomTracker(CHK_UseCustomTracker.Checked);
        RefreshAll();
    }

