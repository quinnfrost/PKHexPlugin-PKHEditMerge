    private void ClearVersionCards()
    {
        foreach (Control c in FLP_Versions.Controls)
        {
            if (c is Panel { Tag: HomeGameDataFormat } card)
            {
                foreach (var pb in card.Controls.OfType<PictureBox>())
                    pb.Image?.Dispose();
