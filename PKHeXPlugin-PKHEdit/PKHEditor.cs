    {
        if (!ConfirmDiscard())
            return false;
        if (!PkhService.TryLoad(path, out var loaded, out var error))
        {
            MessageBox.Show(this, $"Unable to open \"{Path.GetFileName(path)}\": {error}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Warning);
            return false;
        }
        var note = PkhService.HasPC9(loaded) ? " Contains Champions (PC9) data: read-only in this version." : "";
        SetPkh(loaded, path, false, $"Opened {Path.GetFileName(path)}.{note}");
        return true;
    }

