    private bool ConfirmDiscard()
    {
        if (!dirty)
            return true;
        return MessageBox.Show(this, "The current PKH has unsaved changes. Discard them?", BaseTitle, MessageBoxButtons.YesNo, MessageBoxIcon.Warning) == DialogResult.Yes;
    }

    private void SetPkh(PKH value, string? path, bool isDirty, string status)
    {
        pkh = value;
        filePath = path;
        dirty = isDirty;
        L_Status.Text = status;
        RefreshAll();
    }

    /// <summary>Opens <paramref name="path"/> after the usual unsaved-changes prompt. False = cancelled or failed.</summary>
    internal bool OpenFile(string path)
    {
        if (!ConfirmDiscard())
            return false;
        if (!PkhService.TryLoad(path, out var loaded, out var error))
        {
            MessageBox.Show(this, $"Unable to open \"{Path.GetFileName(path)}\": {error}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Warning);
            return false;
        }
        var note = PkhService.HasPC9(loaded) ? " Contains Champions (PC9) data: read-only in this version." : "";
        SetPkh(loaded, path, false, $"Opened {Path.GetFileName(path)}.{note}");
        return true;
    }

    // Read-only surface for the HOME window: the live PKH (never mutated by callers), the save's
    // generation (picks which stored version a box sprite shows) and the save (box wallpaper).
    internal PKH? CurrentPkh => pkh;
    internal Type EditorPkmType => saveProvider.SAV.PKMType;
    internal SaveFile ActiveSave => saveProvider.SAV;

    private bool Save()
    {
        if (pkh == null)
            return false;
        using var dlg = new SaveFileDialog
        {
            Filter = "HOME data (*.pkh)|*.pkh|All files (*.*)|*.*",
            FileName = filePath != null ? Path.GetFileName(filePath) : PathUtil.CleanFileName($"{PkhService.GetDefaultFileName(pkh)}.pkh"),
            InitialDirectory = filePath != null ? Path.GetDirectoryName(filePath) : null,
        };
        if (dlg.ShowDialog(this) != DialogResult.OK)
            return false;
        if (!PkhService.TrySave(pkh, dlg.FileName, out var error))
        {
            MessageBox.Show(this, $"Save failed: {error}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Error);
            return false;
        }
        filePath = dlg.FileName;
        dirty = false;
        L_Status.Text = $"Saved {Path.GetFileName(filePath)} (verified readable by PKHeX).";
        UpdateTitle();
        return true;
    }

    private void B_Save_Click(object? sender, EventArgs e)
    {
        if (pkh != null)
            Save();
    }

    // "Close file": drop the current PKH and return to the freshly opened window state.
    private void B_CloseFile_Click(object? sender, EventArgs e)
    {
        if (pkh == null || !ConfirmDiscard())
            return;
        pkh = null;
        filePath = null;
        dirty = false;
        selected = HomeGameDataFormat.None;
        toolTip1.SetToolTip(L_Status, ""); // drop the last import report tooltip
        L_Status.Text = InitialStatus;
        RefreshAll(); // clears every field, the sprite and the version cards; also disables Save/Close
    }

    private void PKHEditor_FormClosing(object? sender, FormClosingEventArgs e)
    {
        if (!dirty)
            return;
        var answer = MessageBox.Show(this, "Save changes to the PKH before closing?", BaseTitle, MessageBoxButtons.YesNoCancel, MessageBoxIcon.Question);
        if (answer == DialogResult.Cancel || (answer == DialogResult.Yes && !Save()))
            e.Cancel = true;
    }

