    }

    private void RefreshVersionCards(IReadOnlyList<HomeGameDataFormat> versions)
    {
        FLP_Versions.SuspendLayout();
        try
        {
            ClearVersionCards();
            foreach (var format in versions)
                FLP_Versions.Controls.Add(CreateCard(format));
        }
        finally
        {
            FLP_Versions.ResumeLayout();
        }

        RefreshMainSprite();
    }

    // Version selection (which stored version the sprite shows) lives in PkhService.GetPreferredFormat now,
    // so the HOME window can pick sprites the same way.
    private void RefreshMainSprite()
    {
        if (pkh == null)
        {
            SetSprite(PB_Sprite, null);
            return;
        }

        var format = PkhService.GetPreferredFormat(pkh, saveProvider.SAV.PKMType);
        SetSprite(PB_Sprite, format != HomeGameDataFormat.None ? PkhService.Export(pkh, format) : null);
    }

    // The main sprite drags out the whole PKH (not a single version's PKM) — Save/Open/editor import/export are
    // all covered by drag-and-drop, so the equivalent toolbar buttons were removed.
    private void SetupSpriteDragOut()
    {
        PB_Sprite.MouseDown += (_, e) =>
        {
            var size = SystemInformation.DragSize;
            dragBox = e.Button == MouseButtons.Left ? new Rectangle(e.X - (size.Width / 2), e.Y - (size.Height / 2), size.Width, size.Height) : Rectangle.Empty;
        };
        PB_Sprite.MouseUp += (_, _) => dragBox = Rectangle.Empty;
        PB_Sprite.MouseMove += (_, e) =>
        {
            if (e.Button != MouseButtons.Left || dragBox == Rectangle.Empty || dragBox.Contains(e.Location))
                return;
            dragBox = Rectangle.Empty;
            DragOutPkh();
        };
    }

    private void DragOutPkh()
    {
        if (pkh == null)
            return;
        PkmUtil.DragOutPkh(PB_Sprite, pkh);
    }

    private Panel CreateCard(HomeGameDataFormat format)
    {
        var exported = PkhService.Export(pkh!, format);
        var card = new Panel { Size = new Size(88, 100), Margin = new Padding(4), Tag = format, BorderStyle = BorderStyle.FixedSingle, Cursor = Cursors.Hand };
        var pb = new PictureBox { Size = new Size(76, 68), Location = new Point(5, 4), SizeMode = PictureBoxSizeMode.Zoom, Tag = format };
        var label = new Label { Text = format.ToString(), AutoSize = false, TextAlign = ContentAlignment.MiddleCenter, Location = new Point(0, 74), Size = new Size(86, 22), Tag = format };
        pb.Image = exported != null ? PKMSprite.Render(exported) : null;
        card.Controls.Add(pb);
        card.Controls.Add(label);

        var tip = exported == null
            ? $"{format}: export failed"
            : $"{format}: {PkmUtil.GetDisplayName(exported)}\nClick to view, drag out to export as {exported.Extension}.";
        foreach (var c in new Control[] { card, pb, label })
        {
            toolTip1.SetToolTip(c, tip);
            c.Click += (_, _) => SelectVersion(format);
            c.MouseDown += (_, e) =>
            {
                var size = SystemInformation.DragSize;
                dragBox = e.Button == MouseButtons.Left ? new Rectangle(e.X - (size.Width / 2), e.Y - (size.Height / 2), size.Width, size.Height) : Rectangle.Empty;
            };
            c.MouseUp += (_, _) => dragBox = Rectangle.Empty;
            c.MouseMove += (_, e) =>
            {
                if (e.Button != MouseButtons.Left || dragBox == Rectangle.Empty || dragBox.Contains(e.Location))
                    return;
                dragBox = Rectangle.Empty;
                if (pkh != null && PkhService.Export(pkh, format) is { } pk)
                    PkmUtil.DragOut(card, pk);
            };
        }
        return card;
    }

    // Only the version detail panel changes; the main sprite keeps following the active save (RefreshMainSprite).
    private void SelectVersion(HomeGameDataFormat format)
    {
        selected = format;
        RefreshSelectedVersion();
        AutoUpdateCurrentHandler(); // rule 4: auto-judge OT/HT whenever the version selection changes
    }

    /// <summary>Rule 4 (auto Current Handler): only while the selected version is the source version
    /// (the block matching the PKH's origin game) is CurrentHandler judged against the main editor's
    /// save protagonist, using PKHeX's own predicates —
    /// OT side = TradeOT/BelongsTo in full: origin game + both raw IDs (表ID/里ID, the OT/Misc display
    /// pair is a lossless view of ID32) + OT gender + OT name all equal → handler = OT (0);
    /// HT side = IsHandlerSame (HT name+gender equal to the save's OT): the exact TradeHT case that
    /// sets handler = 1 while leaving HT fields untouched — the complementary TradeHT case would also
    /// rewrite HT name/lang/gender/friendship/memories, which is out of scope (CurrentHandler only).
    /// No evidence leaves the imported value untouched; PC9-read-only and no-version states are no-ops.</summary>
    private void AutoUpdateCurrentHandler()
    {
        if (loading || pkh == null || PkhService.HasPC9(pkh))
            return;
        if (selected == HomeGameDataFormat.None || selected != PkhService.GetOriginFormat(pkh.Version))
            return; // not viewing the source version — never touch the field
        var sav = saveProvider.SAV;
        byte? desired;
        if (pkh.Version == sav.Version && pkh.TID16 == sav.TID16 && pkh.SID16 == sav.SID16
            && pkh.OriginalTrainerGender == sav.Gender && pkh.OriginalTrainerName == sav.OT)
            desired = 0; // PKHeX BelongsTo → TradeOT concludes OT
        else if (!pkh.IsUntraded && pkh.HandlingTrainerName == sav.OT && pkh.HandlingTrainerGender == sav.Gender)
            desired = 1; // PKHeX IsHandlerSame → TradeHT concludes HT (no field rewrite needed)
        else
            desired = null; // neither side matches — no evidence, keep the imported value
        if (desired is not { } target || pkh.CurrentHandler == target)
            return;
        Edit(p => p.CurrentHandler = target, $"current handler ({(target == 0 ? "OT" : "HT")})");
    }

    // Reconstructs a missing version from whichever stored version is nearest, exactly like PKHeX does when
    // the main editor's HOME importer needs a version that was never deposited (TryCreate on PKH.ConvertToXX).
    private void B_CreateVersion_Click(object? sender, EventArgs e)
    {
        if (pkh == null || CB_CreateFormat.SelectedItem is not HomeGameDataFormat format)
            return;
        if (PkhService.GetVersions(pkh).Contains(format))
        {
            MessageBox.Show(this, $"{format} is already stored in this PKH.", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Information);
            return;
        }

        var copy = PkhService.Copy(pkh);
        PKM? created;
        try { created = copy.ConvertToPKM(format); }
        catch (Exception ex)
        {
            MessageBox.Show(this, $"PKHeX could not reconstruct {format}: {ex.Message}", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Error);
            return;
        }
        if (created == null)
        {
            MessageBox.Show(this, $"{format} is not reachable from the versions currently stored in this PKH.", BaseTitle, MessageBoxButtons.OK, MessageBoxIcon.Warning);
            return;
        }

        pkh = copy; // ConvertToPKM added the reconstructed block to this copy; adopt it.
        selected = format;
        dirty = true;
        L_Status.Text = $"Reconstructed {format} from the nearest stored version (met location/ball may have been remapped, as HOME does).";
        RefreshAll();
    }

    private void RefreshSelectedVersion()
    {
        foreach (Control c in FLP_Versions.Controls)
            c.BackColor = c.Tag is HomeGameDataFormat f && f == selected ? SystemColors.Highlight : SystemColors.Control;

        if (pkh == null || selected == HomeGameDataFormat.None || PkhService.GetVersionBlock(pkh, selected) is not { } block)
        {
            GB_VersionInfo.Text = "Version data";
            TB_VersionInfo.Text = pkh != null && PkhService.GetVersions(pkh).Count == 0 ? "This PKH has no game version data." : "";
            return;
        }

        // Reflect over the version's own data block: every stored field is listed without a
        // per-version field list (same approach as PkhService.DiffCore's GameDataCore loop).
        // The exported entity is metadata only (origin + context for the location tables) — PKHeX's
        // own conversion supplies both, so no format/version mapping table is maintained here.
        var sample = PkhService.Export(pkh, selected);
        GB_VersionInfo.Text = $"Version data: {selected}";
        var sb = new StringBuilder();
        var seen = new HashSet<string>();
        foreach (var pi in block.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (!PkhService.IsStored(pi) || pi.PropertyType.IsByRefLike || !seen.Add(pi.Name))
                continue;
            sb.AppendLine($"{pi.Name}: {BlockValue(pi, block, sample)}");
        }
        TB_VersionInfo.Text = sb.ToString();
    }

    private static string BlockValue(PropertyInfo pi, object block, PKM? entity)
    {
        // Binary structures show their type instead of a hex dump.
        var type = pi.PropertyType;
        if (type.IsByRefLike || type == typeof(byte[]))
            return $"<{FriendlyTypeName(type)}>";

        object? value;
        try { value = pi.GetValue(block); }
        catch (Exception) { return "<error>"; }
        if (value == null)
            return "-";
        if (value is byte[])
            return $"<{FriendlyTypeName(type)}>";

        // Readable names from PKHeX's tables: locations keep the raw ID, ID fields show the name only.
        string rawText = value.ToString() ?? "-";
        if (value is 0 && PkhService.IsMoveProp(pi.Name))
            return "-"; // empty Move1..4 / RelearnMove1..4 slot
        if (PkhService.ReadableValue(pi.Name, rawText, entity) is { } name)
            return pi.Name is "MetLocation" or "EggLocation" ? $"{rawText} ({name})" : name;

        if (value is IFormattable f) // numbers culture-free, enums by name
            return f.ToString(null, CultureInfo.InvariantCulture) ?? "-";

        // Objects that don't override ToString would only print their type — show a type placeholder.
        var text = value.ToString() ?? "-";
        return value.GetType().GetMethod(nameof(ToString), Type.EmptyTypes)?.DeclaringType == typeof(object)
            ? $"<{FriendlyTypeName(value.GetType())}>"
            : text;
    }

    private static string FriendlyTypeName(Type type)
    {
        if (type.IsArray)
            return FriendlyTypeName(type.GetElementType()!) + "[]";
        if (!type.IsGenericType)
            return type.Name;
        var name = type.Name;
        name = name[..name.IndexOf('`', StringComparison.Ordinal)];
        return $"{name}<{string.Join(", ", type.GetGenericArguments().Select(FriendlyTypeName))}>";
    }

